export function unitAccentColor(unitId: string): string {
  let hash = 0;
  for (let i = 0; i < unitId.length; i++) {
    hash = (hash * 31 + unitId.charCodeAt(i)) >>> 0;
  }
  return UNIT_ACCENT_PALETTE[hash % UNIT_ACCENT_PALETTE.length];
}

